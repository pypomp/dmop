"""Build a separate JRSSB review source from ms.tex without changing its prose.

Run from the repository root: python3 code/build_jrssb.py
Then: make -C .. dmop/ms-jrssb.pdf
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    source = (ROOT / 'ms.tex').read_text()
    abstract = source.split(r'\begin{abstract}', 1)[1].split(r'\end{abstract}', 1)[0].strip()
    body = source[source.index(r'\section{Introduction}'):]
    tables = re.findall(r'\\begin\{table\}(?:\[[^\]]*\])?.*?\\end\{table\}', body, re.S)
    for table in tables:
        body = body.replace(table, '', 1)
    # Wrap hardware descriptions without shrinking the table font.
    tables = [table.replace(r'\begin{tabular}{lll}',
                            r'\begin{tabularx}{\linewidth}{lXX}')
                   .replace(r'\end{tabular}', r'\end{tabularx}')
              if r'\label{table:speedup}' in table else table
              for table in tables]
    # The current source compresses assumption-list labels for the preprint.
    body = body.replace('itemsep=-1ex, , font=\\small', 'itemsep=0pt')
    body = body.replace(r'\end{document}', '\\clearpage\n' + '\n\\clearpage\n'.join(tables) + '\n\\end{document}')
    front = r'''
\begin{document}
\journaltitle{Journals of the Royal Statistical Society}
\DOI{DOI HERE}
\copyrightyear{XXXX}
\pubyear{XXXX}
\access{Advance Access Publication Date: Day Month Year}
\appnotes{Original article}
\firstpage{1}
\title[Differentiable particle filtering]{\articleTitle}
\author[1]{K. Tan}
\author[2]{A. J. Abkemeier}
\author[2]{K. He}
\author[1]{G. Hooker}
\author[2,$\ast$]{E. L. Ionides}
\authormark{Tan et al.}
\address[1]{\orgdiv{Department of Statistics}, \orgname{University of Pennsylvania}, \orgaddress{\country{USA}}}
\address[2]{\orgdiv{Department of Statistics}, \orgname{University of Michigan}, \orgaddress{\country{USA}}}
\corresp[$\ast$]{Address for correspondence: Edward L. Ionides, Department of Statistics, University of Michigan, 1085 South University Avenue, Ann Arbor, MI 48109-1107, USA. \href{mailto:ionides@umich.edu}{ionides@umich.edu}}
\received{Date}{0}{Year}
\revised{Date}{0}{Year}
\accepted{Date}{0}{Year}
\abstract{
'''
    keywords = r'''
}
\keywords{Automatic differentiation; Hidden Markov models; Likelihood inference;
Particle filtering; Sequential Monte Carlo}
\maketitle
'''
    preamble = (ROOT / 'jrssb/preamble.tex').read_text()
    output = '% Generated by code/build_jrssb.py from ms.tex; edit ms.tex for scientific content.\n' + preamble + front + abstract + keywords + body
    (ROOT / 'ms-jrssb.tex').write_text(output)
    print(f'Generated ms-jrssb.tex; preserved abstract and body, moved {len(tables)} tables to the end.')


if __name__ == '__main__':
    main()
